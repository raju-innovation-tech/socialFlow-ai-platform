import 'dart:io';
import 'dart:async';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:socialflow_ai/app/app.dart';
import 'package:socialflow_ai/app/router/app_router.dart';

// 1x1 transparent PNG bytes
final _transparentImage = <int>[
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49,
  0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06,
  0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44,
  0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D,
  0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42,
  0x60, 0x82,
];

class _MockHttpClient extends Fake implements HttpClient {
  @override
  bool autoUncompress = true;

  @override
  Future<HttpClientRequest> getUrl(Uri url) async => _MockHttpClientRequest();
}

class _MockHttpClientRequest extends Fake implements HttpClientRequest {
  @override
  Future<HttpClientResponse> close() async => _MockHttpClientResponse();
}

class _MockHttpClientResponse extends Fake implements HttpClientResponse {
  @override
  int get statusCode => 200;

  @override
  int get contentLength => _transparentImage.length;

  @override
  HttpClientResponseCompressionState get compressionState =>
      HttpClientResponseCompressionState.notCompressed;

  @override
  StreamSubscription<List<int>> listen(
    void Function(List<int> event)? onData, {
    Function? onError,
    void Function()? onDone,
    bool? cancelOnError,
  }) {
    return Stream<List<int>>.value(_transparentImage).listen(
      onData,
      onError: onError,
      onDone: onDone,
      cancelOnError: cancelOnError,
    );
  }
}

class _TestHttpOverrides extends HttpOverrides {
  @override
  HttpClient createHttpClient(SecurityContext? context) => _MockHttpClient();
}

void main() {
  setUpAll(() {
    HttpOverrides.global = _TestHttpOverrides();
  });

  testWidgets('SocialFlow AI app renders properly and boots to dashboard', (WidgetTester tester) async {
    tester.view.physicalSize = const Size(1440, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(
      const ProviderScope(
        child: SocialFlowApp(),
      ),
    );

    await tester.pumpAndSettle();

    expect(find.text('SocialFlow AI'), findsWidgets);
    expect(find.text('Upcoming Posts'), findsOneWidget);
    expect(find.text('Content Calendar'), findsWidgets);
    expect(find.text('Content Pipeline'), findsOneWidget);
    expect(find.text('Approval Queue'), findsOneWidget);
  });

  testWidgets('Navigation routing to Calendar, Campaigns, and Super Admin succeeds', (WidgetTester tester) async {
    tester.view.physicalSize = const Size(1440, 900);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(
      const ProviderScope(
        child: SocialFlowApp(),
      ),
    );
    await tester.pumpAndSettle();

    // Navigate to Calendar
    appRouter.go('/calendar');
    await tester.pumpAndSettle();
    expect(find.text('Plan, reschedule, and visualize automated omni-channel campaigns.'), findsOneWidget);

    // Navigate to Campaigns
    appRouter.go('/campaigns');
    await tester.pumpAndSettle();
    expect(find.text('Multi-Channel Campaigns'), findsOneWidget);

    // Navigate to Super Admin
    appRouter.go('/super-admin/dashboard');
    await tester.pumpAndSettle();
    expect(find.text('Super Admin Control Plane'), findsOneWidget);

    // Navigate to Login
    appRouter.go('/login');
    await tester.pumpAndSettle();
    expect(find.text('Sign in to your omni-channel workspace'), findsOneWidget);
  });
}
